#!/usr/bin/env python3
"""Generate the synthetic mechanism-map table (issue64) for the appendix.

Rows = five synthetic ground-truth regimes; columns = selected orderings.
Entry = robust win count over the 15 pool-budget cells (3 pools x 5 design
budgets), where a robust win means the calibrated calls beat the
design-marginal reference with a bootstrap interval excluding zero.
"""
import csv, os, collections

import pathlib
REPO_ROOT=pathlib.Path(__file__).resolve().parents[2]
ROLL=str(REPO_ROOT/'results'/'paper_rollups')
OUTP=str(REPO_ROOT/'figures_out'/'paper')
pathlib.Path(OUTP).mkdir(parents=True,exist_ok=True)
SRC=os.path.join(ROLL,'mechanism_first_wins.csv')
REPO=OUTP
OUT=OUTP

REG={'conditional_independence_heterogeneous_difficulty':'conditional independence, mixed difficulty',
     'mixed_easy_hard_pooled_correlation_no_residual':'pooled correlation, no residual dependence',
     'redundant_families_positive_residual':'redundant families (positive residual)',
     'complementary_specialists_negative_residual':'complementary specialists (negative residual)',
     'higher_order_pairwise_invisible':'higher-order, pairwise-invisible'}
CAND=[('empirical_tally','tally'),('pairwise_count','pairwise count'),('error_correlation','error corr.'),
      ('latent_normal','latent normal'),('query_local_empirical_coverage','query-local')]

rows=list(csv.DictReader(open(SRC)))
agg=collections.defaultdict(lambda:[0,0,None])
for r in rows:
    k=(r['regime'],r['candidate'])
    agg[k][0]+=int(r['robust_win_budget_count'])
    agg[k][1]+=int(r['budgets_evaluated'])
    f=r['first_robust_win_design_budget']
    if f:
        f=int(f)
        if agg[k][2] is None or f<agg[k][2]: agg[k][2]=f

L=[]
L.append("% AUTO-GENERATED by build_mechanism_table.py (issue64).")
L.append(r"\begin{table}[t]")
L.append(r"\centering")
L.append(r"\caption{Synthetic mechanism map. Each regime generates model correctness with a known ground-truth dependence structure; entries count the pool-budget cells, out of 15 (three pool sizes, five design budgets from 50 to 1{,}000 labels), where the ordering beats the design-marginal reference with a bootstrap interval excluding zero. The two independence regimes are clean negative controls: no dependence-aware ordering wins any cell there, so the real-data gains are not an artifact of the machinery.}")
L.append(r"\label{tab:mechanism-map}")
L.append(r"\scriptsize")
L.append(r"\setlength{\tabcolsep}{4pt}")
L.append(r"\begin{tabular}{@{}l ccccc@{}}")
L.append(r"\toprule")
L.append(r"ground-truth regime & "+" & ".join(l for _,l in CAND)+r" \\")
L.append(r"\midrule")
csvrows=[]
for reg_code,reg_label in REG.items():
    cells=[]
    for cand,_ in CAND:
        w,t,first=agg[(reg_code,cand)]
        s=f"{w}/{t}"
        if w>=10: s=r"\textbf{"+s+"}"
        cells.append(s)
        csvrows.append({'regime':reg_code,'candidate':cand,'robust_wins':w,'cells':t,'first_win_budget':first})
    L.append(reg_label+" & "+" & ".join(cells)+r" \\")
L.append(r"\bottomrule")
L.append(r"\end{tabular}")
L.append(r"\end{table}")
open(REPO+'/appendix_mechanism_map.tex','w').write("\n".join(L)+"\n")
with open(os.path.join(OUT,'mechanism_map_data.csv'),'w',newline='') as f:
    w=csv.DictWriter(f,fieldnames=list(csvrows[0])); w.writeheader(); w.writerows(csvrows)
print("wrote mechanism map table")
