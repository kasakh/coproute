#!/usr/bin/env python3
"""Generate the estimator-family tables and the appendix result tables.

Outputs (all under figures_out/paper):
  tables/estimator_family_main.tex   compact main-paper comparison of
                                     alternative orders against the tally
                                     order, both stopping rules
  tables/appendix_certified_pools.tex  RouterEval pools 200/300/500 certified
                                       calls for all six policies, alphas
                                       0.05 and 0.10
  tables/appendix_estimator_grid.tex   full order-by-pool grid, both arms
  tables/appendix_mathint.tex          MATH-intermediate certification rates

Sources: issue78 stage1 rollup (orders), issue62 rollup (policies, tally
Dep-vs-Ind chaining), both canonical.
"""
import csv, json, os, statistics as st

import pathlib
REPO_ROOT=pathlib.Path(__file__).resolve().parents[2]
ROLL=str(REPO_ROOT/'results'/'paper_rollups')
OUTP=str(REPO_ROOT/'figures_out'/'paper')
pathlib.Path(OUTP).mkdir(parents=True,exist_ok=True)
F78=os.path.join(ROLL,'estimator_grid_uncertainty.csv')
F62=os.path.join(ROLL,'certified_calls_uncertainty.csv')
REPO=OUTP
r78=list(csv.DictReader(open(F78)))
r62=list(csv.DictReader(open(F62)))

NAMES={'bernoulli_mixture':'Bernoulli mixture','student_t_copula':'Student-t copula',
 'gaussian_copula':'Gaussian copula','rank_correlation':'rank correlation',
 'double_fault':'double fault','factor_copula':'low-rank factor copula',
 'shrinkage_factor':'shrinkage to one factor','shrinkage_indep':'shrinkage to independence',
 'error_correlation':'error correlation','lineage':'model-family lineage',
 'accuracy_weighted_random':'accuracy-weighted random','seeded_random':'random control'}
POOLS=[11,100,200,300,500]

tally={}
for r in r62:
    if r['method']=='fixed_tally_chain_discounted' and r['reference_method']=='fixed_tally_factorized' and r['paired_mean_calls_difference']!='':
        tally[(r['benchmark'],r['pool_size'],r['target_alpha'])]=float(r['paired_mean_calls_difference'])
idx={}
for r in r78:
    if r['paired_mean_calls_difference']=='' or not r['paired_certified_redraw_count'] or int(r['paired_certified_redraw_count'])==0: continue
    idx[(r['method'],r['reference_method'],r['benchmark'],r['pool_size'],r['target_alpha'])]=(float(r['paired_mean_calls_difference']),int(r['paired_certified_redraw_count']))

def agg(order,arm,pool=None):
    num=den=0.0
    for (m,ref,b,p,a),(d,n) in idx.items():
        if b=='math_intermediate_algebra_hard': continue
        if pool is not None and int(p)!=pool: continue
        if arm=='ind':
            if m!=f'fixed_{order}_factorized' or ref!='fixed_tally_factorized': continue
        else:
            if m!=f'fixed_{order}_chain_discounted' or ref!=f'fixed_{order}_factorized': continue
            k2=(f'fixed_{order}_factorized','fixed_tally_factorized',b,p,a)
            if k2 not in idx or (b,p,a) not in tally: continue
            d=d+idx[k2][0]-tally[(b,p,a)]
        num+=d*n; den+=n
    return num/den if den else None

def fnum(v):
    if v is None: return '--'
    return f"{v:+.2f}"

# ---- main-paper table -------------------------------------------------------
MAIN_ORDERS=['bernoulli_mixture','student_t_copula','gaussian_copula','rank_correlation',
             'double_fault','error_correlation','accuracy_weighted_random','seeded_random']
L=[]
L.append("% AUTO-GENERATED by build_estimator_tables.py (issue78 + issue62 rollups). Regenerate, do not hand-edit.")
L.append(r"\begin{table}[t]")
L.append(r"\centering")
L.append(r"\caption{The CopRoute family with alternative dependence estimators. Each entry is the certified-redraw-weighted mean of the paired extra calls relative to the tally order under the same stopping rule, over the ten datasets and all pools (``all'') or the 100-model pool alone; negative means fewer calls than the tally order. Ind is independence-based stopping and Dep is dependence-corrected stopping. The random control uses a seeded random order.}")
L.append(r"\label{tab:estimator-family}")
L.append(r"\scriptsize")
L.append(r"\setlength{\tabcolsep}{4pt}")
L.append(r"\begin{tabular}{@{}l rr rr@{}}")
L.append(r"\toprule")
L.append(r" & \multicolumn{2}{c}{vs tally, Ind stopping} & \multicolumn{2}{c}{vs tally, Dep stopping} \\")
L.append(r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}")
L.append(r"order & all pools & pool 100 & all pools & pool 100 \\")
L.append(r"\midrule")
csvrows=[]
for o in MAIN_ORDERS:
    v=[agg(o,'ind'),agg(o,'ind',100),agg(o,'dep'),agg(o,'dep',100)]
    csvrows.append({'order':o,'ind_all':v[0],'ind_p100':v[1],'dep_all':v[2],'dep_p100':v[3]})
    cells=[]
    for x in v:
        s=fnum(x)
        if x is not None and x<0: s=r"\textbf{"+s+"}"
        cells.append(s)
    L.append(NAMES[o]+" & "+" & ".join(cells)+r" \\")
L.append(r"\bottomrule")
L.append(r"\end{tabular}")
L.append(r"\end{table}")
open(os.path.join(REPO,'estimator_family_main.tex'),'w').write("\n".join(L)+"\n")

# ---- appendix: full estimator grid -----------------------------------------
A=[]
A.append("% AUTO-GENERATED by build_estimator_tables.py.")
A.append(r"\begin{table}[t]")
A.append(r"\centering")
A.append(r"\caption{Complete order-by-pool grid for the CopRoute family. Entries are certified-redraw-weighted mean paired extra calls relative to the tally order under the same stopping rule; negative means fewer calls than tally. Aggregation covers the ten datasets of Table~\ref{tab:main-calls} over the seven calibration targets.}")
A.append(r"\label{tab:estimator-grid}")
A.append(r"\scriptsize")
A.append(r"\setlength{\tabcolsep}{2.6pt}")
A.append(r"\begin{tabular}{@{}l rrrrrr@{\hspace{10pt}}rrrrrr@{}}")
A.append(r"\toprule")
A.append(r" & \multicolumn{6}{c}{independence-based stopping} & \multicolumn{6}{c}{dependence-corrected stopping} \\")
A.append(r"\cmidrule(lr){2-7}\cmidrule(lr){8-13}")
A.append(r"order & all & p11 & p100 & p200 & p300 & p500 & all & p11 & p100 & p200 & p300 & p500 \\")
A.append(r"\midrule")
for o in NAMES:
    cells=[]
    for arm in ['ind','dep']:
        for p in [None]+POOLS:
            cells.append(fnum(agg(o,arm,p)))
