# ---- appendix: per-pool certified calls (RouterEval 200/300/500) ------------
REB=[('bbh_boolean_expressions','BBH-boolean'),('bbh_navigate','BBH-navigate'),
     ('gpqa_diamond','GPQA'),('ifeval','IFEval'),('math_algebra_hard','MATH-algebra'),('musr','MuSR')]
def cell62(bench,pool,alpha):
    sub=[r for r in r62 if r['benchmark']==bench and int(r['pool_size'])==pool and r['target_alpha']==alpha]
    out={}
    for r in sub:
        if r['method']=='fixed_tally_chain_discounted':
            if r['reference_method']=='fixed_tally_factorized':
                if r['method_certified_mean_calls']: out['Dep']=(float(r['method_certified_mean_calls']),float(r['method_certification_rate']))
                if r['reference_certified_mean_calls']: out['Ind']=(float(r['reference_certified_mean_calls']),float(r['reference_certification_rate']))
            if r['reference_method']=='racer_g' and r['reference_certified_mean_calls']:
                out['RACER-G']=(float(r['reference_certified_mean_calls']),float(r['reference_certification_rate']))
            if r['reference_method']=='racer_p' and r['reference_certified_mean_calls']:
                out['RACER-P']=(float(r['reference_certified_mean_calls']),float(r['reference_certification_rate']))
    for fam,name in [('flexrouter','FlexRouter'),('barp','BaRP')]:
        vals=[];certs=[]
        for s in range(9101,9106):
            for r in sub:
                if r['method']==f'{fam}_seed_{s}' and r['reference_method']=='fixed_tally_factorized' and r['method_certified_mean_calls']:
                    vals.append(float(r['method_certified_mean_calls']));certs.append(float(r['method_certification_rate']))
        if vals: out[name]=(st.mean(vals),st.mean(certs))
    return out
POL=['Ind','Dep','RACER-G','RACER-P','FlexRouter','BaRP']
B=[]
B.append("% AUTO-GENERATED by build_estimator_tables.py.")
B.append(r"\begin{table}[t]")
B.append(r"\centering")
B.append(r"\caption{Certified mean calls on the RouterEval benchmarks at the 200-, 300-, and 500-model pools, completing Table~\ref{tab:main-calls}. A dagger marks cells whose certification rate is below 0.9; a dash means no redraw certifies.}")
B.append(r"\label{tab:pools-certified}")
B.append(r"\scriptsize")
B.append(r"\setlength{\tabcolsep}{3pt}")
B.append(r"\begin{tabular}{@{}ll rrrrrr @{\hspace{10pt}} rrrrrr@{}}")
B.append(r"\toprule")
B.append(r" & & \multicolumn{6}{c}{$\alpha=0.05$} & \multicolumn{6}{c}{$\alpha=0.10$} \\")
B.append(r"\cmidrule(lr){3-8}\cmidrule(lr){9-14}")
B.append(r"dataset & pool & Ind & Dep & G & P & Flex. & BaRP & Ind & Dep & G & P & Flex. & BaRP \\")
B.append(r"\midrule")
def f2(v):
    return f"{v:.1f}" if v>=10 else f"{v:.2f}"
for bench,label in REB:
    for pool in [200,300,500]:
        row=[label if pool==200 else '', str(pool)]
        for alpha in ['0.05','0.1']:
            c=cell62(bench,pool,alpha)
            best=min((v[0] for m,v in c.items() if m in POL), default=None)
            for m in POL:
                v=c.get(m)
                if v is None: row.append('--'); continue
                s=f2(v[0])
                if v[1]<0.9: s=s+r"$^\dagger$"
                if best is not None and f2(v[0])==f2(best): s=r"\textbf{"+s+"}"
                row.append(s)
        B.append(" & ".join(row)+r" \\")
    B.append(r"\addlinespace[2pt]")
B.append(r"\bottomrule")
B.append(r"\end{tabular}")
B.append(r"\end{table}")
open(os.path.join(REPO,'appendix_certified_pools.tex'),'w').write("\n".join(B)+"\n")

