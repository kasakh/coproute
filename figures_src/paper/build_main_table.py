#!/usr/bin/env python3
"""Generate the main certified-calls table for the CopRoute paper.

Source of truth: the issue62 canonical rollup (e2_uncertainty.csv).
Output: LaTeX table* with two side-by-side subtables (alpha 0.05, 0.10),
10 datasets x 6 policies. Best value(s) per row share a green cell;
the next distinct value is underlined. Brackets: SE for single-router
policies, across-5-seed SD for FlexRouter and BaRP.
Also writes data.csv with every number used.
"""
import csv, statistics as st, os

import pathlib
REPO_ROOT=pathlib.Path(__file__).resolve().parents[2]
ROLL=str(REPO_ROOT/'results'/'paper_rollups')
OUTP=str(REPO_ROOT/'figures_out'/'paper')
pathlib.Path(OUTP).mkdir(parents=True,exist_ok=True)
SRC=os.path.join(ROLL,'certified_calls_uncertainty.csv')
OUT_DIR=OUTP
TEX_OUT=os.path.join(OUT_DIR,'main_certified_calls.tex')

BENCH=[('arc-challenge',11,'ARC'),('hellaswag',11,'HellaSwag'),('mmlu',11,'MMLU'),
       ('winogrande',11,'WinoGrande'),
       ('bbh_boolean_expressions',100,'BBH-boolean'),('bbh_navigate',100,'BBH-navigate'),
       ('gpqa_diamond',100,'GPQA'),('ifeval',100,'IFEval'),
       ('math_algebra_hard',100,'MATH-algebra'),('musr',100,'MuSR')]
POLICIES=['Ind','Dep','RACER-G','RACER-P','FlexRouter','BaRP']

rows=list(csv.DictReader(open(SRC)))

def cell(bench,pool,alpha):
    sub=[r for r in rows if r['benchmark']==bench and int(r['pool_size'])==pool and r['target_alpha']==alpha]
    out={}
    for r in sub:
        if r['method']=='fixed_tally_chain_discounted':
            if r['reference_method']=='fixed_tally_factorized':
                out['Dep']=(float(r['method_certified_mean_calls']),float(r['method_certified_calls_se']),float(r['method_certification_rate']))
                out['Ind']=(float(r['reference_certified_mean_calls']),float(r['reference_certified_calls_se']),float(r['reference_certification_rate']))
            if r['reference_method']=='racer_g':
                out['RACER-G']=(float(r['reference_certified_mean_calls']),float(r['reference_certified_calls_se']),float(r['reference_certification_rate']))
            if r['reference_method']=='racer_p':
                out['RACER-P']=(float(r['reference_certified_mean_calls']),float(r['reference_certified_calls_se']),float(r['reference_certification_rate']))
    for fam,name in [('flexrouter','FlexRouter'),('barp','BaRP')]:
        vals=[];certs=[]
        for s in range(9101,9106):
            for r in sub:
                if r['method']==f'{fam}_seed_{s}' and r['reference_method']=='fixed_tally_factorized' and r['method_certified_mean_calls']:
                    vals.append(float(r['method_certified_mean_calls']));certs.append(float(r['method_certification_rate']))
        if vals:
            out[name]=(st.mean(vals), st.stdev(vals) if len(vals)>1 else 0.0, st.mean(certs))
    return out

def fmt(v):
    return f"{v:.1f}" if v>=10 else f"{v:.2f}"

def build_subtable(alpha, data_rows):
    lines=[]
    lines.append(r"\begin{subtable}[t]{0.495\textwidth}")
    lines.append(r"\centering")
    lines.append(r"\caption{Target risk $\alpha=%s$.}" % ('0.05' if alpha=='0.05' else '0.10'))
    lines.append(r"\label{tab:main-calls-%s}" % alpha.replace('.',''))
    lines.append(r"\setlength{\tabcolsep}{2.5pt}")
    lines.append(r"\resizebox{\linewidth}{!}{%")
    lines.append(r"\begin{tabular}{@{}l rrrrrr@{}}")
    lines.append(r"\toprule")
    lines.append(r" & \multicolumn{2}{c}{CopRoute} & \multicolumn{2}{c}{RACER} & & \\")
    lines.append(r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}")
    lines.append(r"dataset & Ind & Dep & G & P & Flex. & BaRP \\")
    lines.append(r"\midrule")
    for label,vals,marks in data_rows:
        cells=[]
        for m in POLICIES:
            v=vals.get(m)
            if v is None:
                cells.append('--'); continue
            s=f"{fmt(v[0])} ({fmt(v[1])})"
            if marks[m]=='best':
                s=r"\cellcolor{green!18}"+s
            elif marks[m]=='second':
                s=r"\underline{"+s+"}"
            cells.append(s)
        lines.append(label+" & "+" & ".join(cells)+r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}}")
    lines.append(r"\end{subtable}")
    return lines

def marks_for(vals):
    """Display-value ties share best; second = next distinct display value."""
    disp={m:fmt(v[0]) for m,v in vals.items() if v}
    uniq=sorted({float(d) for d in disp.values()})
    best=uniq[0]; second=uniq[1] if len(uniq)>1 else None
    marks={}
    for m,d in disp.items():
        f=float(d)
        marks[m]='best' if f==best else ('second' if second is not None and f==second else '')
    return marks

all_lines=[]
all_lines.append("% AUTO-GENERATED by build_main_table.py on 2026-09-21 from the issue62 rollup.")
all_lines.append("% Do not edit numbers by hand; regenerate instead.")
all_lines.append(r"\begin{table}[t]")
all_lines.append(r"\centering")
all_lines.append(r"\caption{Certified mean calls at matched target risk, lower is better. Each entry is the mean over certified redraws with its dispersion in brackets: standard error for CopRoute and RACER, standard deviation across five training seeds for FlexRouter and BaRP. The \colorbox{green!18}{best} value in each row is shaded, with exact ties shaded together, and the next distinct value is \underline{underlined}. RouterBench datasets (first four rows) use the 11-model pool; RouterEval datasets use the 100-model pool. At $\alpha=0.05$ every method certifies all 20 redraws except on IFEval (19), MATH-algebra (3), and MuSR (8), identically across methods; at $\alpha=0.10$ all cells certify all 20 redraws.}")
all_lines.append(r"\label{tab:main-calls}")
all_lines.append(r"\scriptsize")

csv_rows=[]
for k,alpha in enumerate(['0.05','0.1']):
    data_rows=[]
    for bench,pool,label in BENCH:
        vals=cell(bench,pool,alpha)
        marks=marks_for(vals)
        data_rows.append((label,vals,marks))
        for m in POLICIES:
            v=vals.get(m)
            if v: csv_rows.append({'alpha':alpha,'dataset':label,'pool':pool,'policy':m,
                                   'certified_mean_calls':v[0],'dispersion':v[1],'certification_rate':v[2],'mark':marks[m]})
    all_lines.extend(build_subtable(alpha,data_rows))
    if k==0: all_lines.append(r"\hfill")
all_lines.append(r"\end{table}")

os.makedirs(os.path.dirname(TEX_OUT),exist_ok=True)
open(TEX_OUT,'w').write("\n".join(all_lines)+"\n")
with open(os.path.join(OUT_DIR,'main_table_data.csv'),'w',newline='') as f:
    w=csv.DictWriter(f,fieldnames=list(csv_rows[0]))
    w.writeheader(); w.writerows(csv_rows)
print(f"wrote {TEX_OUT} and data.csv ({len(csv_rows)} rows)")
# sanity: win counts for our policies
for alpha in ['0.05','0.1']:
    wins=0
    for bench,pool,label in BENCH:
        vals=cell(bench,pool,alpha); marks=marks_for(vals)
        if marks.get('Ind')=='best' or marks.get('Dep')=='best': wins+=1
    print(f"alpha {alpha}: CopRoute best in {wins}/10 rows")
