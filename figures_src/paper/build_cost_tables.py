#!/usr/bin/env python3
"""Generate the cost and cascade appendix tables.

  tables/appendix_cost_case_study.tex    issue66: calls, end-to-end accuracy,
                                         and public-price cost per query with
                                         redraw SEs, RouterBench MMLU pool 11
  tables/appendix_cost_weighted.tex      issue70: cost-weighted vs
                                         count-optimized stopping, paired
                                         differences with bootstrap CI95
  tables/appendix_cascade.tex            issue58: cascade risk vs matched
                                         CopRoute-Ind risk
"""
import csv, os

import pathlib
REPO_ROOT=pathlib.Path(__file__).resolve().parents[2]
ROLL=str(REPO_ROOT/'results'/'paper_rollups')
OUTP=str(REPO_ROOT/'figures_out'/'paper')
pathlib.Path(OUTP).mkdir(parents=True,exist_ok=True)
R=ROLL
REPO=OUTP

# ---- issue66 cost case study -------------------------------------------------
NAME={'fixed_tally_factorized':'CopRoute-Ind','fixed_tally_chain_discounted':'CopRoute-Dep',
      'exact_independence':'exact independence','fixed_design_marginal_factorized':'design-marginal order',
      'racer_g':'RACER-G','racer_p':'RACER-P',
      'all_models_router_top':'call every model','best_single_design':'best single model'}
ORDER=['fixed_tally_factorized','fixed_tally_chain_discounted','racer_g','racer_p',
       'exact_independence','fixed_design_marginal_factorized','all_models_router_top','best_single_design']
rows=list(csv.DictReader(open(R+'/cost_case_study.csv')))
def r66(alpha,method):
    for r in rows:
        if r['target_alpha']==alpha and r['method']==method: return r
    return None
L=[]
L.append("% AUTO-GENERATED by build_cost_tables.py (issue66 case study).")
L.append(r"\begin{table}[t]")
L.append(r"\centering")
L.append(r"\caption{Cost and end-to-end accuracy case study on RouterBench MMLU (11-model pool, 20 redraws, every calibrated policy certifies all redraws at both targets). The answer returned is the called model's response with the highest router score, so accuracy here is final-answer accuracy, not coverage; cost prices every call with the archived public price sheet. Brackets are standard errors over redraws. The \colorbox{green!18}{best} calibrated value per column is shaded. The last two rows are fixed reference policies reported without calibration; the single-model reference misses 18.6 percent of queries, far above both targets, so it admits no certificate at these risk levels.}")
L.append(r"\label{tab:cost-case-study}")
L.append(r"\scriptsize")
L.append(r"\setlength{\tabcolsep}{3.2pt}")
L.append(r"\begin{tabular}{@{}l rrr @{\hspace{12pt}} rrr@{}}")
L.append(r"\toprule")
L.append(r" & \multicolumn{3}{c}{$\alpha=0.05$} & \multicolumn{3}{c}{$\alpha=0.10$} \\")
L.append(r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}")
L.append(r"policy & calls & accuracy (\%) & cost (USD/1k) & calls & accuracy (\%) & cost (USD/1k) \\")
L.append(r"\midrule")
CAL=ORDER[:6]
def best(alpha,key,lo=True):
    vals=[float(r66(alpha,m)[key]) for m in CAL]
    return min(vals) if lo else max(vals)
for m in ORDER:
    if m=='all_models_router_top': L.append(r"\midrule")
    cells=[NAME[m]]
    for a in ['0.05','0.1']:
        r=r66(a,m)
        calls=float(r['mean_calls']); cse=float(r['mean_calls_se_redraw'])
        acc=100*float(r['final_answer_accuracy']); ase=100*float(r['final_answer_accuracy_se_redraw'])
        cost=1000*float(r['mean_public_price_cost_usd']); qse=1000*float(r['mean_cost_se_redraw'])
        c1=f"{calls:.2f} ({cse:.2f})"; c2=f"{acc:.2f} ({ase:.2f})"; c3=f"{cost:.2f} ({qse:.2f})"
        if m in CAL:
            if calls==best(a,'mean_calls'): c1=r"\cellcolor{green!18}"+c1
            if abs(acc-100*best(a,'final_answer_accuracy',lo=False))<1e-9: c2=r"\cellcolor{green!18}"+c2
            if abs(cost-1000*best(a,'mean_public_price_cost_usd'))<1e-9: c3=r"\cellcolor{green!18}"+c3
        cells+= [c1,c2,c3]
    L.append(" & ".join(cells)+r" \\")
L.append(r"\bottomrule")
L.append(r"\end{tabular}")
L.append(r"\end{table}")
open(REPO+'/appendix_cost_case_study.tex','w').write("\n".join(L)+"\n")

# ---- issue70 cost-weighted ---------------------------------------------------
pr=list(csv.DictReader(open(R+'/cost_weighted_paired.csv')))
mrows=list(csv.DictReader(open(R+'/cost_weighted_methods.csv')))
TASKS=[('arc-challenge','ARC'),('hellaswag','HellaSwag'),('mmlu','MMLU'),('winogrande','WinoGrande')]
def mcost(task,alpha,method):
    for r in mrows:
        if r['task']==task and r['target_alpha']==alpha and r['method']==method:
            return 1000*float(r['actual_archived_mean_cost'])
    return None
L=[]
L.append("% AUTO-GENERATED by build_cost_tables.py (issue70).")
L.append(r"\begin{table}[t]")
L.append(r"\centering")
L.append(r"\caption{Cost-weighted stopping on RouterBench (archived public prices, 20 redraws, all cells certified). The cost-weighted variant replaces the call count in the stopping objective with the price-weighted sum while keeping the same order and calibration. Left: certified mean cost per 1{,}000 queries in USD. Right: paired difference of the cost-weighted variant against count-optimized CopRoute-Ind with bootstrap 95 percent intervals; every cost interval excludes zero, so the cost reduction is systematic, purchased with the stated extra calls.}")
L.append(r"\label{tab:cost-weighted}")
L.append(r"\scriptsize")
L.append(r"\setlength{\tabcolsep}{2.8pt}")
L.append(r"\begin{tabular}{@{}ll rrr @{\hspace{12pt}} rr@{}}")
L.append(r"\toprule")
L.append(r" & & \multicolumn{3}{c}{cost, USD per 1k queries} & \multicolumn{2}{c}{cost-weighted minus CopRoute-Ind} \\")
L.append(r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}")
L.append(r"dataset & $\alpha$ & cost-weighted & CopRoute-Ind & RACER-G & $\Delta$cost [CI95] & $\Delta$calls [CI95] \\")
L.append(r"\midrule")
for task,label in TASKS:
    for a in ['0.05','0.1']:
        cw=mcost(task,a,'cost_weighted_tally_factorized'); ti=mcost(task,a,'fixed_tally_factorized'); rg=mcost(task,a,'racer_g')
        d=None
        for r in pr:
            if (r['task']==task and r['target_alpha']==a and r['candidate']=='cost_weighted_tally_factorized'
                and r['reference']=='fixed_tally_factorized'):
                d=r; break
        dc=1000*float(d['cost_mean_difference']); lo=1000*float(d['cost_ci95_low']); hi=1000*float(d['cost_ci95_high'])
        dk=float(d['calls_mean_difference']); klo=float(d['calls_ci95_low']); khi=float(d['calls_ci95_high'])
        L.append(f"{label if a=='0.05' else ''} & {'0.05' if a=='0.05' else '0.10'} & "
                 f"\\cellcolor{{green!18}}{cw:.3f} & {ti:.3f} & {rg:.3f} & "
                 f"{dc:+.3f} [{lo:+.3f}, {hi:+.3f}] & {dk:+.2f} [{klo:+.2f}, {khi:+.2f}] \\\\")
    L.append(r"\addlinespace[2pt]")
L.append(r"\bottomrule")
L.append(r"\end{tabular}")
L.append(r"\end{table}")
open(REPO+'/appendix_cost_weighted.tex','w').write("\n".join(L)+"\n")

# ---- issue58 cascade ----------------------------------------------------------
crows=list(csv.DictReader(open(R+'/cascade_summary.csv')))
BN={'arc-challenge':'ARC (pool 11)','gpqa_diamond':'GPQA (pool 100)','ifeval':'IFEval (pool 100)','math_algebra_hard':'MATH-algebra (pool 100)'}
L=[]
L.append("% AUTO-GENERATED by build_cost_tables.py (issue58).")
L.append(r"\begin{table}[t]")
L.append(r"\centering")
L.append(r"\caption{Cascade routing under the archived-correctness protocol. The cascade's stopping rule needs response-derived quality signals that archived correctness matrices do not contain, so the honestly available version degenerates to a pre-response router. Entries are realized all-miss risk on the same splits as the matched CopRoute-Ind; a starred value exceeds the target. The cascade carries no distribution-free certificate in any cell.}")
L.append(r"\label{tab:cascade}")
L.append(r"\scriptsize")
L.append(r"\begin{tabular}{@{}l rr @{\hspace{12pt}} rr@{}}")
L.append(r"\toprule")
L.append(r" & \multicolumn{2}{c}{$\alpha=0.05$} & \multicolumn{2}{c}{$\alpha=0.10$} \\")
L.append(r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}")
L.append(r"dataset & cascade & CopRoute-Ind & cascade & CopRoute-Ind \\")
L.append(r"\midrule")
def c58(bench,alpha):
    for r in crows:
        if r['benchmark']==bench and r['target_alpha']==alpha and r['matched_reference']=='fixed_tally_factorized':
            return r
for bench,label in BN.items():
    cells=[label]
    for a in ['0.05','0.1']:
        r=c58(bench,a)
        cr=float(r['cascade_standard_all_miss_risk']); rr=float(r['reference_standard_all_miss_risk'])
        s1=f"{cr:.3f}"+("$^*$" if r['cascade_empirically_at_or_below_target']=='False' else "")
        s2=f"{rr:.3f}"+("$^*$" if r['reference_empirically_at_or_below_target']=='False' else "")
        cells+=[s1,s2]
    L.append(" & ".join(cells)+r" \\")
L.append(r"\bottomrule")
L.append(r"\end{tabular}")
L.append(r"\end{table}")
open(REPO+'/appendix_cascade.tex','w').write("\n".join(L)+"\n")
print("wrote 3 cost/cascade tables")
