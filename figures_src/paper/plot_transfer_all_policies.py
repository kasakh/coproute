#!/usr/bin/env python3
"""Appendix transfer assets: per-policy RouterEval premium heatmaps and the
cross-policy transfer summary table.

Premium(cell) = target-recalibrated certified calls when fit on the row
dataset minus the same policy's in-domain calls on the column dataset,
alpha 0.10, pool 100. One panel per policy. Also writes the summary table
(mean fit premium per suite and source-calibrated risk inflation) from the
issue52 cross-suite closure.
"""
import csv, glob, os, re, statistics as st
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

import pathlib
REPO_ROOT=pathlib.Path(__file__).resolve().parents[2]
ROLL=str(REPO_ROOT/'results'/'paper_rollups')
OUTP=str(REPO_ROOT/'figures_out'/'paper')
pathlib.Path(OUTP).mkdir(parents=True,exist_ok=True)
OUT=OUTP
FIGDIR=OUTP
REPO=OUTP
RE_DIR=os.path.join(ROLL,'transfer','routereval')
XSUITE=os.path.join(ROLL,'transfer_cross_suite_summary.csv')
ALPHA='0.1'
REV=[('bbh_boolean_expressions','BBH-b'),('bbh_navigate','BBH-n'),('gpqa_diamond','GPQA'),
     ('ifeval','IFEval'),('math_algebra_hard','MATH-a'),('musr','MuSR')]
POLICIES=[('CopRoute-Ind','fixed_tally_factorized'),('CopRoute-Dep','fixed_tally_chain_discounted'),
          ('RACER-G','racer_g'),('RACER-P','racer_p'),('FlexRouter','flexrouter'),('BaRP','barp')]

def get_calls(f,method):
    if method in ('flexrouter','barp'):
        vals=[]
        for r in csv.DictReader(open(f)):
            if r['alpha']==ALPHA and r['method'].startswith(method+'_seed') and r['target_recalibrated_mean_calls']:
                vals.append(float(r['target_recalibrated_mean_calls']))
        return st.mean(vals) if vals else None
    for r in csv.DictReader(open(f)):
        if r['alpha']==ALPHA and r['method']==method and r['target_recalibrated_mean_calls']:
            return float(r['target_recalibrated_mean_calls'])
    return None

def fpath(src,tgt,mode):
    fs=glob.glob(os.path.join(RE_DIR,f'{src}_to_{tgt}_{mode}_pool100_analysis.csv'))
    return fs[0] if fs else None

fig,axes=plt.subplots(2,3,figsize=(9.6,6.0))
data_rows=[]
vmax=12.0
for ax,(pname,mcode) in zip(axes.flat,POLICIES):
    n=len(REV)
    M=np.full((n,n),np.nan)
    for i,(s,_) in enumerate(REV):
        for j,(t,_) in enumerate(REV):
            mode='in_domain' if s==t else 'source_fitted'
            f=fpath(s,t,mode); fin=fpath(t,t,'in_domain')
            if not f or not fin: continue
            c=get_calls(f,mcode); cin=get_calls(fin,mcode)
            if c is not None and cin is not None:
                M[i,j]=c-cin
                data_rows.append({'policy':pname,'source':s,'target':t,'premium':c-cin,
                                  'source_fitted_calls':c,'in_domain_calls':cin})
    im=ax.imshow(np.clip(M,0,vmax),cmap='Reds',vmin=0,vmax=vmax)
    labs=[l for _,l in REV]
    ax.set_xticks(range(n),labs,rotation=45,ha='right',fontsize=6.5)
    ax.set_yticks(range(n),labs,fontsize=6.5)
    ax.set_title(pname,fontsize=9)
    for i in range(n):
        for j in range(n):
            if np.isnan(M[i,j]):
                ax.add_patch(plt.Rectangle((j-0.5,i-0.5),1,1,color='0.92'))
                ax.text(j,i,'n/r',ha='center',va='center',fontsize=5.8,color='0.4')
            else:
                ax.text(j,i,f"{M[i,j]:+.1f}" if i!=j else "0",ha='center',va='center',fontsize=5.8,
                        color='white' if M[i,j]>0.65*vmax else 'black')
fig.suptitle('extra certified calls after out-of-domain fitting, recalibrated on the target (RouterEval pool 100, target risk 0.10)',fontsize=9,y=0.99)
fig.tight_layout(rect=[0,0,1,0.97])
fig.savefig(os.path.join(FIGDIR,'ood_premium_all_policies.pdf'),dpi=300,bbox_inches='tight')
fig.savefig(os.path.join(OUT,'ood_premium_all_policies.png'),dpi=200,bbox_inches='tight')
with open(os.path.join(OUT,'ood_premium_all_policies_data.csv'),'w',newline='') as f:
    w=csv.DictWriter(f,fieldnames=list(data_rows[0])); w.writeheader(); w.writerows(data_rows)

# summary table
NAME={'fixed_tally_factorized':'CopRoute-Ind','fixed_tally_chain_discounted':'CopRoute-Dep',
      'racer_g':'RACER-G','racer_p':'RACER-P','flexrouter':'FlexRouter','barp':'BaRP'}
L=[]
L.append("% AUTO-GENERATED by plot_appendix.py (issue52 cross-suite closure).")
L.append(r"\begin{table}[t]")
L.append(r"\centering")
L.append(r"\caption{Cross-dataset transfer summary per policy. The fit premium is the mean extra certified calls when the policy is fit on one dataset and deployed, recalibrated, on another within the same suite. Risk inflation is the mean amount by which the realized risk exceeds the target when a source-calibrated cutoff is reused without recalibration; it is positive for every policy, so recalibration on the deployment distribution is required in all cases.}")
L.append(r"\label{tab:transfer-summary}")
L.append(r"\scriptsize")
L.append(r"\begin{tabular}{@{}l rr rr@{}}")
L.append(r"\toprule")
L.append(r" & \multicolumn{2}{c}{fit call premium} & \multicolumn{2}{c}{source-calibrated risk inflation} \\")
L.append(r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}")
L.append(r"policy & RouterBench & RouterEval & RouterBench & RouterEval \\")
L.append(r"\midrule")
order=['fixed_tally_factorized','fixed_tally_chain_discounted','racer_g','racer_p','flexrouter','barp']
xs={r['method_family']:r for r in csv.DictReader(open(XSUITE))}
for m in order:
    r=xs[m]
    L.append(f"{NAME[m]} & {float(r['routerbench_fit_call_premium']):+.2f} & {float(r['routereval_fit_call_premium']):+.2f} & "
             f"{float(r['routerbench_source_calibrated_risk_inflation']):+.3f} & {float(r['routereval_source_calibrated_risk_inflation']):+.3f} \\\\")
L.append(r"\bottomrule")
L.append(r"\end{tabular}")
L.append(r"\end{table}")
open(os.path.join(REPO,'appendix_transfer_summary.tex'),'w').write("\n".join(L)+"\n")
print('wrote all-policy transfer figure + summary table,',len(data_rows),'cells')
